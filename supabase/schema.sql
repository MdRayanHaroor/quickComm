ON CONFLICT (id) DO NOTHING;

-- ============================================================
-- 3. BRANDS TABLE
-- ============================================================
CREATE TABLE IF NOT EXISTS public.brands (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id    bigint REFERENCES public.stores(id) ON DELETE CASCADE DEFAULT 1,
  name        text NOT NULL,
  logo_url    text,
  is_active   boolean DEFAULT true,
  created_at  timestamptz DEFAULT now() NOT NULL,
  UNIQUE (store_id, name)
);

CREATE INDEX IF NOT EXISTS idx_brands_store ON public.brands(store_id);

-- ============================================================
-- 4. CATEGORIES TABLE (Hierarchical Tree)
-- ============================================================
CREATE TABLE IF NOT EXISTS public.categories (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id    bigint REFERENCES public.stores(id) ON DELETE CASCADE DEFAULT 1,
  name        text NOT NULL,
  slug        text NOT NULL,
  parent_id   bigint REFERENCES public.categories(id) ON DELETE SET NULL,
  image_url   text,
  sort_order  int DEFAULT 0,
  is_active   boolean DEFAULT true,
  created_at  timestamptz DEFAULT now() NOT NULL,
  UNIQUE (store_id, slug)
);

CREATE INDEX IF NOT EXISTS idx_categories_parent ON public.categories(parent_id);
CREATE INDEX IF NOT EXISTS idx_categories_slug ON public.categories(store_id, slug);
CREATE INDEX IF NOT EXISTS idx_categories_store ON public.categories(store_id);

-- ============================================================
-- 5. PRODUCTS TABLE
-- ============================================================
CREATE TABLE IF NOT EXISTS public.products (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_id     bigint REFERENCES public.stores(id) ON DELETE CASCADE DEFAULT 1,
  name         text NOT NULL,
  slug         text,
  description  text,
  size         text,
  price        numeric DEFAULT 0,
  category     text NOT NULL DEFAULT 'Main Course',
  category_id  bigint REFERENCES public.categories(id) ON DELETE SET NULL,
  brand_id     bigint REFERENCES public.brands(id) ON DELETE SET NULL,
  image_url    text,
  images       text[] DEFAULT '{}',
  tags         text[] DEFAULT '{}',
  gst_rate     numeric DEFAULT 0,
  is_available boolean DEFAULT true,
  created_at   timestamptz DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at   timestamptz DEFAULT now() NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_products_store_slug ON public.products(store_id, slug)
  WHERE slug IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_products_category ON public.products(category_id);
CREATE INDEX IF NOT EXISTS idx_products_brand ON public.products(brand_id);
CREATE INDEX IF NOT EXISTS idx_products_store ON public.products(store_id);
CREATE INDEX IF NOT EXISTS idx_products_available ON public.products(is_available) WHERE is_available = true;

-- Full-text search index
CREATE INDEX IF NOT EXISTS idx_products_fts ON public.products
  USING gin(to_tsvector('english', coalesce(name, '') || ' ' || coalesce(description, '')));

-- ============================================================
-- 6. PRODUCT VARIANTS TABLE
-- ============================================================
CREATE TABLE IF NOT EXISTS public.product_variants (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id        bigint REFERENCES public.products(id) ON DELETE CASCADE NOT NULL,
  sku               text,
  barcode           text,
  variant_name      text NOT NULL,
  unit_value        numeric,
  unit_type         text,
  mrp               numeric NOT NULL,
  selling_price     numeric NOT NULL,
  stock_quantity    int DEFAULT 0 CHECK (stock_quantity >= 0),
  low_stock_alert   int DEFAULT 10,
  is_available      boolean DEFAULT true,
  image_url         text,
  sort_order        int DEFAULT 0,
  created_at        timestamptz DEFAULT now() NOT NULL,
  updated_at        timestamptz DEFAULT now() NOT NULL,
  CONSTRAINT selling_price_lte_mrp CHECK (selling_price <= mrp),
  UNIQUE (product_id, variant_name)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_variants_sku ON public.product_variants(sku) WHERE sku IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_variants_product ON public.product_variants(product_id);
CREATE INDEX IF NOT EXISTS idx_variants_available ON public.product_variants(is_available) WHERE is_available = true;

-- ============================================================
-- 7. ORDERS TABLE
-- ============================================================
CREATE TABLE IF NOT EXISTS public.orders (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id           uuid REFERENCES public.profiles(id) NOT NULL,
  rider_id          uuid REFERENCES public.profiles(id),
  status            text CHECK (status IN ('pending', 'confirmed', 'preparing', 'out_for_delivery', 'delivered', 'cancelled')) NOT NULL DEFAULT 'pending',
  total_amount      numeric NOT NULL,
  delivery_fee      numeric DEFAULT 0,
  discount_amount   numeric DEFAULT 0,
  coupon_code       text,
  payment_method    text CHECK (payment_method IN ('cod', 'upi', 'card', 'wallet', 'netbanking')) DEFAULT 'cod',
  payment_status    text CHECK (payment_status IN ('pending', 'paid', 'failed', 'refunded')) DEFAULT 'pending',
  delivery_address  text NOT NULL,
  delivery_lat      float,
  delivery_lng      float,
  delivery_notes    text,
  delivered_at      timestamptz,
  created_at        timestamptz DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at        timestamptz DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_orders_payment_status ON public.orders(payment_status);
CREATE INDEX IF NOT EXISTS idx_orders_status ON public.orders(status);
CREATE INDEX IF NOT EXISTS idx_orders_user_id ON public.orders(user_id);
CREATE INDEX IF NOT EXISTS idx_orders_rider_id ON public.orders(rider_id);

-- ============================================================
