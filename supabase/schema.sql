-- Function: Handle New User Signup
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, full_name, role)
  VALUES (NEW.id, NEW.raw_user_meta_data->>'full_name', 'user')
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- Function: Audit Rider Location History
CREATE OR REPLACE FUNCTION public.log_rider_location_history()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.rider_location_history (
    rider_id, order_id, lat, lng, speed, heading, accuracy, recorded_at
  ) VALUES (
    NEW.rider_id, NEW.order_id, NEW.lat, NEW.lng,
    COALESCE(NEW.speed, 0), COALESCE(NEW.heading, 0), COALESCE(NEW.accuracy, 0),
    COALESCE(NEW.last_updated, now())
  );
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_rider_location_upsert ON public.rider_locations;
CREATE TRIGGER on_rider_location_upsert
  AFTER INSERT OR UPDATE ON public.rider_locations
  FOR EACH ROW EXECUTE FUNCTION public.log_rider_location_history();

-- Function: Auto Set updated_at
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS products_set_updated_at ON public.products;
CREATE TRIGGER products_set_updated_at
  BEFORE UPDATE ON public.products
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS variants_set_updated_at ON public.product_variants;
CREATE TRIGGER variants_set_updated_at
  BEFORE UPDATE ON public.product_variants
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- Function: Enforce Single Default Address
CREATE OR REPLACE FUNCTION public.enforce_single_default_address()
RETURNS TRIGGER AS $$
BEGIN
  IF NEW.is_default = true THEN
    UPDATE public.customer_addresses
    SET is_default = false
    WHERE user_id = NEW.user_id AND id != NEW.id;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_address_default_set ON public.customer_addresses;
CREATE TRIGGER on_address_default_set
  AFTER INSERT OR UPDATE OF is_default ON public.customer_addresses
  FOR EACH ROW
  WHEN (NEW.is_default = true)
  EXECUTE FUNCTION public.enforce_single_default_address();

-- Function: Decrement Variant Stock Safely
CREATE OR REPLACE FUNCTION public.decrement_variant_stock(p_variant_id bigint, p_quantity int)
RETURNS void AS $$
BEGIN
  UPDATE public.product_variants
  SET stock_quantity = GREATEST(0, stock_quantity - p_quantity),
      updated_at = now()
  WHERE id = p_variant_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Function: Restore Variant Stock
CREATE OR REPLACE FUNCTION public.increment_variant_stock(p_variant_id bigint, p_quantity int)
RETURNS void AS $$
BEGIN
  UPDATE public.product_variants
  SET stock_quantity = stock_quantity + p_quantity,
      updated_at = now()
  WHERE id = p_variant_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

